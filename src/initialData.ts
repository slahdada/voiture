/**
 * Crée une copie fraîche des données historiques adaptées à un identifiant utilisateur donné.
 */
export function getInitialHistoricalData(userId?: string): State {
  const cloned: State = JSON.parse(JSON.stringify(HISTORICAL_INITIAL_DATA));
  if (userId) {
    cloned.userId = userId;
    for (const v of cloned.vehicles) {
      v.userId = userId;
    }
    for (const e of cloned.entries) {
      e.userId = userId;
    }
    for (const d of cloned.deadlines) {
      d.userId = userId;
    }
  }
  return cloned;
}
